"use strict";
const assert=require("node:assert/strict");
const m=require("../functions/cgweb139");
const noisy=Array.from({length:266},(_,i)=>({altitude_m:106+5*(i%6)/5,distance_m:i*38}));
const input={payload:{points:noisy.map(x=>({...x})),total_ascent_m:0}};
const before=JSON.stringify(noisy);
const r=m.prepare({ascent_m:0,record_count:1058},{source_point_count:1058,lat:noisy.map(_=>46),lon:noisy.map(_=>6)},input);
assert.equal(r.report.candidate_fit_record_count,266);
assert.deepEqual(r.blockers,["SOURCE_RECORD_COUNT_MISMATCH"]);
assert.equal(r.report.altitude_mode,"ZERO_ASCENT_HIGH_CONFIDENCE_NOISE_FLATTENED");
assert.equal(input.payload.total_ascent_m,0);
assert.equal(new Set(input.payload.points.map(x=>x.altitude_m)).size,1);
assert.equal(JSON.stringify(noisy),before,"Original must not be changed");
const intact={payload:{points:noisy.map(x=>({...x}))}};
const ok=m.prepare({ascent_m:78,record_count:266},{source_point_count:266,lat:noisy.map(_=>46)},intact);
assert.deepEqual(ok.blockers,[]);
assert.equal(ok.report.altitude_mode,"RAW_ALTITUDE_PRESERVED");
assert.equal(intact.payload.total_ascent_m,78);
assert.ok(new Set(intact.payload.points.map(x=>x.altitude_m)).size>1);
const zero={payload:{points:[{altitude_m:101},{altitude_m:104}]}};
const z=m.prepare({ascent_m:0},{source_point_count:2},zero);
assert.deepEqual(z.blockers,[]);
assert.equal(zero.payload.total_ascent_m,0);
const missing=m.prepare({ascent_m:null},{source_point_count:2},{payload:{points:[{altitude_m:100},{altitude_m:101}]}});
assert.ok(missing.blockers.includes("CANONICAL_ASCENT_UNAVAILABLE"));
const audit=m.altitudeAudit({activity:{ascent_m:0},route:{source_point_count:1058},preview:{fit:{ascent_m:0,record_count:266}},strava:{total_elevation_gain:0}});
assert.equal(audit.status,"ASCENT_MATCH");
assert.equal(audit.record_parity_ok,false);
console.log("CGWEB139 TESTS PASS — canonical ascent, plateau noise, raw preservation, downsample blocker, altitude audit");
